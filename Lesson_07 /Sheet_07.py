"""
while_loop_counter.py
---------------------

This script demonstrates the use of a `while` loop to print numbers
from 1 to 50. It shows how a counter variable is incremented in each
iteration until the loop condition becomes false.
"""


# ---------------------------------------------------------------------
# WHILE LOOP EXAMPLE
# ---------------------------------------------------------------------

i = 1

while i < 51:
    print(i)
    i += 1  # Equivalent to: i = i + 1
