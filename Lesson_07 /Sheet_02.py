"""
range_and_while_loop_demo.py
----------------------------

This script demonstrates:
1. A `for` loop using `range()` with a placeholder `pass` statement.
2. A `while` loop that prints numbers from 0 to 44.

The `pass` statement is commonly used as a placeholder when a loop or
function is syntactically required but no action is currently needed.
"""


# ---------------------------------------------------------------------
# FOR LOOP WITH PASS
# ---------------------------------------------------------------------

for i in range(645):
    pass  # Placeholder (no operation performed)


# ---------------------------------------------------------------------
# WHILE LOOP
# ---------------------------------------------------------------------

i = 0
while i < 45:
    print(i)
    i += 1
